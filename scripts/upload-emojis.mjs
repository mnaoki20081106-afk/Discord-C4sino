// Application Emoji バッチアップローダ。
// - assets/ 下の全 PNG を Discord Application Emoji として登録する
// - 既に同名のものがあれば skip (name は filename のベース)
// - 全件完了後、name→id の辞書を src/ui/emoji-ids.ts に書き出す
//
// 必要 env:
//   DISCORD_TOKEN       (Bot Token)
//   DISCORD_CLIENT_ID   (= Application ID)
//
// 使い方:
//   node scripts/upload-emojis.mjs

import 'dotenv/config';
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';

const TOKEN = process.env.DISCORD_TOKEN;
const APP_ID = process.env.DISCORD_CLIENT_ID;
if (!TOKEN || !APP_ID) {
  console.error('DISCORD_TOKEN and DISCORD_CLIENT_ID must be set in .env');
  process.exit(1);
}

const API = 'https://discord.com/api/v10';
const HEADERS = {
  Authorization: `Bot ${TOKEN}`,
  'Content-Type': 'application/json',
};

/** 既存の Application Emoji 一覧を取得 */
async function listEmojis() {
  const res = await fetch(`${API}/applications/${APP_ID}/emojis`, { headers: HEADERS });
  if (!res.ok) throw new Error(`list failed ${res.status}: ${await res.text()}`);
  const j = await res.json();
  return j.items ?? [];
}

/** 新規アップロード */
async function uploadEmoji(name, pngBuffer) {
  const dataUrl = `data:image/png;base64,${pngBuffer.toString('base64')}`;
  const res = await fetch(`${API}/applications/${APP_ID}/emojis`, {
    method: 'POST',
    headers: HEADERS,
    body: JSON.stringify({ name, image: dataUrl }),
  });
  if (res.status === 429) {
    const r = await res.json().catch(() => ({}));
    const retry = Math.ceil((r.retry_after ?? 2) * 1000);
    console.log(`  rate limited, waiting ${retry}ms…`);
    await new Promise(r => setTimeout(r, retry));
    return uploadEmoji(name, pngBuffer);
  }
  if (!res.ok) throw new Error(`upload ${name} failed ${res.status}: ${await res.text()}`);
  return res.json();
}

function walkAssets(root = 'assets') {
  const out = [];
  function walk(dir) {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      const st = statSync(full);
      if (st.isDirectory()) walk(full);
      else if (name.endsWith('.png')) out.push(full);
    }
  }
  walk(root);
  return out;
}

/** ファイル名 (拡張子除去) をそのまま emoji name として使う (ASCII, 英数字 + _) */
function nameFor(path) {
  const base = path.split('/').pop().replace(/\.png$/, '');
  if (!/^[a-z0-9_]+$/.test(base)) {
    throw new Error(`invalid emoji name "${base}" (ascii lower + digit + _ only). file: ${path}`);
  }
  if (base.length < 2 || base.length > 32) {
    throw new Error(`emoji name length must be 2-32: "${base}"`);
  }
  return base;
}

const files = walkAssets();
console.log(`Found ${files.length} PNG files under assets/`);

const existing = await listEmojis();
const byName = new Map(existing.map(e => [e.name, e]));
console.log(`Application already has ${existing.length} emoji(s)`);

const idMap = {};
let uploaded = 0, skipped = 0, failed = 0;

for (const f of files) {
  const name = nameFor(f);
  const cached = byName.get(name);
  if (cached) {
    idMap[name] = cached.id;
    skipped++;
    continue;
  }
  try {
    const buf = readFileSync(f);
    if (buf.length > 256 * 1024) {
      console.warn(`[skip] ${name}: ${buf.length} bytes > 256KB Discord limit`);
      failed++;
      continue;
    }
    const e = await uploadEmoji(name, buf);
    idMap[name] = e.id;
    console.log(`[+] ${name}  id=${e.id}`);
    uploaded++;
    // 短いスリープで rate limit を予防 (Discord は 5 req/5s 程度まで許容)
    await new Promise(r => setTimeout(r, 300));
  } catch (err) {
    console.error(`[x] ${name}: ${err.message}`);
    failed++;
  }
}

// 既存だがローカルにないものは別途ログ (手動掃除用)
const localNames = new Set(files.map(nameFor));
const orphans = existing.filter(e => !localNames.has(e.name));
if (orphans.length) {
  console.log(`\nOrphan emojis (exist on application but not in assets/):`);
  for (const o of orphans) console.log(`  ${o.name}  id=${o.id}`);
}

// name→id 辞書を TS に出力
const outPath = 'src/ui/emoji-ids.ts';
mkdirSync(dirname(outPath), { recursive: true });
const lines = [
  '// Auto-generated by scripts/upload-emojis.mjs. DO NOT EDIT MANUALLY.',
  '// Re-run `node scripts/upload-emojis.mjs` to refresh after new emojis.',
  '',
  `export const EMOJI_IDS = ${JSON.stringify(idMap, null, 2)} as const;`,
  '',
  'export type EmojiName = keyof typeof EMOJI_IDS;',
  '',
  '/** `<:name:id>` 形式の Discord 絵文字タグを返す。存在しない name は空文字。 */',
  'export function emoji(name: string): string {',
  '  const id = (EMOJI_IDS as Record<string, string>)[name];',
  '  return id ? `<:${name}:${id}>` : "";',
  '}',
  '',
].join('\n');
writeFileSync(outPath, lines);
console.log(`\nWrote ${Object.keys(idMap).length} entries to ${outPath}`);
console.log(`Summary: uploaded=${uploaded} skipped(existing)=${skipped} failed=${failed}`);
